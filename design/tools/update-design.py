# git access (index)

def git(*args, input_bytes=None, check=True):
    p = subprocess.run(["git"] + list(args), input=input_bytes, stdout=subprocess.PIPE,
                       stderr=subprocess.PIPE)
    if check and p.returncode != 0:
        raise RuntimeError("git %s failed: %s" % (" ".join(args), p.stderr.decode("utf-8", "replace").strip()))
    return p.stdout


class Index:
    """Tracked files and their staged contents, read with one `git cat-file --batch`."""

    def __init__(self):
        out = git("ls-files", "-s", "-z").decode("utf-8", "replace")
        self.blobs = {}
        for entry in out.split("\0"):
            if not entry:
                continue
            meta, path = entry.split("\t", 1)
            mode, sha, stage = meta.split()
            if stage != "0":
                raise RuntimeError("index has unmerged entries (%s)" % path)
            self.blobs[path] = sha
        self.cache = {}

    def files(self, prefix):
        return sorted(p for p in self.blobs if p.startswith(prefix))

    def load(self, paths):
        need = [p for p in paths if p not in self.cache and p in self.blobs]
        if not need:
            return
        data = git("cat-file", "--batch", input_bytes=("\n".join(self.blobs[p] for p in need) + "\n").encode())
        pos = 0
        for p in need:
            nl = data.index(b"\n", pos)
            header = data[pos:nl].split()
            size = int(header[2])
            body = data[nl + 1: nl + 1 + size]
            pos = nl + 1 + size + 1
            self.cache[p] = body

    def text(self, path):
        self.load([path])
        b = self.cache.get(path)
        return None if b is None else b.decode("utf-8", "replace")


def tree_hash(prefix):
    """Tree hash of a folder as staged (equals `git rev-parse HEAD:<folder>` once committed)."""
    return git("write-tree", "--prefix=%s/" % prefix).decode().strip()


def head_tree_hash(prefix):
    out = git("rev-parse", "--verify", "-q", "HEAD:%s" % prefix, check=False).decode().strip()
    return out or None


def last_change_date(prefix, pending):
    """Date of the commit that last changed the folder; the pending commit's date if it is
    being changed right now (same value CI computes afterwards with git log)."""
    if pending:
        ident = git("var", "GIT_COMMITTER_IDENT").decode().strip()
        m = re.search(r"(\d+) ([+-])(\d\d)(\d\d)$", ident)
        if m:
            off = (int(m.group(3)) * 60 + int(m.group(4))) * (1 if m.group(2) == "+" else -1)
            tz = datetime.timezone(datetime.timedelta(minutes=off))
            return datetime.datetime.fromtimestamp(int(m.group(1)), tz).strftime("%Y-%m-%d")
    out = git("log", "-1", "--format=%cs", "--", prefix + "/", check=False).decode().strip()
    return out or "uncommitted"


