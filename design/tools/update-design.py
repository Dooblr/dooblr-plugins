# small C++ text helpers

_COMMENT_RE = re.compile(r'"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\'|//[^\n]*|/\*.*?(?:\*/|\Z)', re.S)
_STRIP_CACHE = {}


def strip_comments(src):
    """Blank out comments (keeping offsets and newlines) but keep string literals."""
    hit = _STRIP_CACHE.get(src)
    if hit is not None:
        return hit

    def blank(m):
        t = m.group(0)
        if t[0] in "\"'":
            return t
        return re.sub(r"[^\n]", " ", t)
    out = _COMMENT_RE.sub(blank, src)
    _STRIP_CACHE[src] = out
    return out


OPEN = {"(": ")", "{": "}", "[": "]"}


def match(src, i):
    """Index of the bracket closing the one at src[i] (strings skipped)."""
    stack = [OPEN[src[i]]]
    j = i + 1
    n = len(src)
    while j < n and stack:
        c = src[j]
        if c == '"' or c == "'":
            q = c
            j += 1
            while j < n and src[j] != q:
                j += 2 if src[j] == "\\" else 1
        elif c in OPEN:
            stack.append(OPEN[c])
        elif c == stack[-1]:
            stack.pop()
            if not stack:
                return j
        j += 1
    return n - 1


def split_top(s, sep=","):
    parts, depth, cur, i = [], 0, [], 0
    while i < len(s):
        c = s[i]
        if c == '"' or c == "'":
            q = c
            j = i + 1
            while j < len(s) and s[j] != q:
                j += 2 if s[j] == "\\" else 1
            cur.append(s[i:j + 1])
            i = j + 1
            continue
        if c in "({[":
            depth += 1
        elif c in ")}]":
            depth -= 1
        if depth == 0 and s.startswith(sep, i) and not (sep == "+" and (s[i - 1:i] in "+e" or s[i + 1:i + 2] == "+")) \
                and not (sep == ":" and (s[i - 1:i] == ":" or s[i + 1:i + 2] == ":")):
            parts.append("".join(cur).strip())
            cur = []
            i += len(sep)
            continue
        cur.append(c)
        i += 1
    tail = "".join(cur).strip()
    if tail or parts:
        parts.append(tail)
    return parts


def squash(s):
    return re.sub(r"\s+", " ", s).strip()


def num(s):
    """'0.10f' -> '0.1', '100.0f' -> '100'."""
    def one(m):
        t = m.group(0).rstrip("fF")
        if "." in t and "e" not in t.lower():
            t = t.rstrip("0").rstrip(".")
        return t or "0"
    return re.sub(r"(?<![\w.])[-+]?\d+\.\d*(?:[eE][-+]?\d+)?[fF]?|(?<![\w.])\d+[fF](?!\w)", one, s)


def tidy(expr):
    e = squash(expr)
    e = e.replace("juce::", "").replace("std::", "")
    e = re.sub(r"\s*([(),{}])\s*", r"\1", e)
    e = e.replace(",", ", ")
    e = re.sub(r"\(\s*(float|int|double|size_t)\s*\)\s*", "", e)
    return num(e)


KEYWORDS = {"if", "for", "while", "switch", "catch", "return", "sizeof", "decltype", "static_assert",
            "alignof", "noexcept", "else", "do", "case", "new", "delete", "throw", "operator"}


class Func:
    def __init__(self, name, params, body_start, body_end, kind):
        self.name, self.params, self.start, self.end, self.kind = name, params, body_start, body_end, kind
        self.ret = None


def param_names(plist):
    names = []
    for p in split_top(plist):
        p = p.split("=")[0].strip()
        m = re.search(r"([A-Za-z_]\w*)\s*(\[[^\]]*\])?$", p)
        if m and p not in ("void", ""):
            names.append(m.group(1))
    return names


def find_functions(code):
    funcs = []
    for m in re.finditer(r"([A-Za-z_]\w*)\s*\(", code):
        name = m.group(1)
        if name in KEYWORDS:
            continue
        po = m.end() - 1
        pc = match(code, po)
        rest = code[pc + 1: pc + 200]
        mm = re.match(r"\s*(?:const\s*)?(?:noexcept\s*)?(?:override\s*)?(?:mutable\s*)?(?:->\s*[\w:<>&*\s]+?)?\s*\{", rest)
        if not mm:
            continue
        before = code[max(0, m.start() - 160):m.start()].rstrip()
        lam = re.search(r"([A-Za-z_]\w*)\s*=\s*\[[^\]]*\]\s*$", before)
        if lam:
            name, kind = lam.group(1), "lambda"
        elif re.search(r"[\w>&*]$", before) and not re.search(r"\b(return|else|new)$", before):
            kind = "func"
            name = name.split("::")[-1]
        else:
            continue
        bo = pc + 1 + mm.end() - 1
        be = match(code, bo)
        f = Func(name, param_names(code[po + 1:pc]), bo, be, kind)
        body = code[bo + 1:be].strip()
        r = re.fullmatch(r"return\s+(.*?);", body, re.S)
        if r:
            f.ret = r.group(1).strip()
        funcs.append(f)
    for m in re.finditer(r"\b([A-Za-z_]\w*)\s*=\s*\[[^\]]*\]\s*\(", code):
        po = m.end() - 1
        pc = match(code, po)
        mm = re.match(r"\s*(?:mutable\s*)?(?:noexcept\s*)?(?:->\s*[\w:<>&*\s]+?)?\s*\{", code[pc + 1: pc + 200])
        if not mm:
            continue
        bo = pc + 1 + mm.end() - 1
        be = match(code, bo)
        f = Func(m.group(1), param_names(code[po + 1:pc]), bo, be, "lambda")
        r = re.fullmatch(r"return\s+(.*?);", code[bo + 1:be].strip(), re.S)
        if r:
            f.ret = r.group(1).strip()
        funcs.append(f)
    funcs.sort(key=lambda f: f.start)
    return funcs


def numeric_constants(code):
    """name -> {value} for constexpr numbers, including  constexpr float a = 1, b = 2;"""
    out = {}
    for m in re.finditer(r"constexpr\s+(?:static\s+)?(?:const\s+)?(?:int|float|double|auto|size_t|std::size_t)\s+([^;]*);", code):
        for part in split_top(m.group(1)):
            mm = re.fullmatch(r"\s*(\w+)\s*(?:=\s*|\{\s*)([-+]?\d[\d.]*(?:[eE][-+]?\d+)?[fF]?)\s*\}?\s*", part)
            if mm:
                out.setdefault(mm.group(1), set()).add(num(mm.group(2)))
    return out


def loop_ranges(code, start, end):
    """(start, end, header) for every for-loop body between start and end."""
    out = []
    for m in re.finditer(r"\bfor\s*\(", code[start:end]):
        po = start + m.end() - 1
        pc = match(code, po)
        header = code[po + 1:pc]
        k = pc + 1
        while k < end and code[k].isspace():
            k += 1
        if k < end and code[k] == "{":
            be = match(code, k)
        else:
            be = stmt_end(code, k)
        out.append((pc, be, header))
    return out


def stmt_end(code, k):
    """Index of the ';' that ends the statement starting at k (brackets and strings skipped)."""
    n = len(code)
    while k < n:
        c = code[k]
        if c in OPEN or c in "\"'":
            k = match(code, k) + 1 if c in OPEN else k + 1
            if c in "\"'":
                while k < n and code[k] != c:
                    k += 2 if code[k] == "\\" else 1
                k += 1
            continue
        if c == ";":
            return k
        k += 1
    return n - 1


def branch_ranges(code, start, end):
    """[(body_start, body_end, own_cond or None, [earlier conds in the chain])] for if/else chains."""
    out = []
    taken = set()

    def body_after(k):
        while k < end and code[k].isspace():
            k += 1
        if k < end and code[k] == "{":
            return k, match(code, k)
        return k, stmt_end(code, k)

    for m in re.finditer(r"\bif\s*\(", code[start:end]):
        at = start + m.start()
        if at in taken:
            continue
        chain = []
        k = at
        while True:
            po = code.index("(", k)
            pc = match(code, po)
            cond = squash(code[po + 1:pc])
            bs, be = body_after(pc + 1)
            out.append((bs, be, cond, list(chain)))
            chain.append(cond)
            n = re.match(r"\s*else\b", code[be + 1:be + 40])
            if not n:
                break
            k = be + 1 + n.end()
            nn = re.match(r"\s*if\s*\(", code[k:k + 40])
            if nn:
                taken.add(k + nn.start() + len(code[k:k + 40]) - len(code[k:k + 40].lstrip()))
                k = k + nn.start()
                continue
            bs, be = body_after(k)
            out.append((bs, be, None, list(chain)))
            break
    return out


def decide(cond):
    """True / False when a substituted condition compares two known constants, else None."""
    m = re.fullmatch(r"\(?\s*([\w:.\-]+)\s*(==|!=)\s*([\w:.\-]+)\s*\)?", cond)
    if not m:
        return None
    a, op, b = m.groups()
    known = lambda x: "::" in x or re.fullmatch(r"-?\d+(\.\d+)?", x)
    if not (known(a) and known(b)):
        return None
    return (a == b) == (op == "==")


