# parameter extraction (static, best effort; templated ids keep {n} placeholders)

AP_TYPES = {"AudioParameterFloat": "float", "AudioParameterBool": "bool", "AudioParameterChoice": "choice",
            "AudioParameterInt": "int"}
ROLES = {"float": ["id", "name", "range", "default"], "bool": ["id", "name", "default"],
         "choice": ["id", "name", "choices", "default"], "int": ["id", "name", "lo", "hi", "default"]}


class ParamParser:
    def __init__(self, cpp, headers_text, all_source_text):
        self.raw = cpp
        self.code = strip_comments(cpp)
        self.funcs = find_functions(self.code)
        self.by_name = {}
        for f in self.funcs:
            self.by_name.setdefault(f.name, []).append(f)
        for f in find_functions(strip_comments(headers_text)):
            if f.kind == "func" and f.ret and f.name not in self.by_name:
                self.by_name[f.name] = [Func(f.name, f.params, 0, 0, "func")]
                self.by_name[f.name][0].ret = f.ret
        self.aliases = {}
        for m in re.finditer(r"using\s+(\w+)\s*=\s*(?:juce::)?(AudioParameter\w+)\s*;", self.code):
            self.aliases[m.group(1)] = m.group(2)
        self.strings = {}
        for m in re.finditer(r"constexpr\s+(?:const\s+)?char\s*(?:const\s*)?\*\s*(\w+)\s*=\s*\"([^\"]*)\"",
                             strip_comments(headers_text) + "\n" + self.code):
            self.strings.setdefault(m.group(1), set()).add(m.group(2))
        self.numbers = numeric_constants(strip_comments(all_source_text))
        self.str_arrays = {}
        for m in re.finditer(r"std::array\s*<\s*const char\s*\*\s*,[^>]*>\s*(\w+)\s*\{([^}]*)\}",
                             strip_comments(headers_text)):
            self.str_arrays[m.group(1)] = re.findall(r'"([^"]*)"', m.group(2))

    # --- helpers
    def enclosing(self, pos):
        best = None
        for f in self.funcs:
            if f.start < pos < f.end and (best is None or f.start > best.start):
                best = f
        return best

    def outer_func(self, pos):
        best = None
        for f in self.funcs:
            if f.kind == "func" and f.start < pos < f.end and (best is None or f.start < best.start):
                best = f
        return best

    def lookup_fn(self, name, pos):
        cands = self.by_name.get(name, [])
        if not cands:
            return None
        lam = [f for f in cands if f.kind == "lambda" and f.start < pos]
        if lam:
            outer = self.outer_func(pos)
            lam = [f for f in lam if outer is None or (outer.start < f.start < outer.end)]
            if lam:
                return max(lam, key=lambda f: f.start)
        funcs = [f for f in cands if f.kind == "func"]
        return funcs[0] if funcs else None

    def local_var(self, name, pos):
        outer = self.outer_func(pos)
        lo = outer.start if outer else 0
        best = None
        for m in re.finditer(r"\b(?:const\s+)?(?:auto|juce::String|bool|int|float)\s*&?\s+" + re.escape(name) +
                             r"\s*=\s*([^;]+);", self.code[lo:pos]):
            if "[" not in m.group(1)[:1]:
                best = (lo + m.start(), m.group(1))
        for m in re.finditer(r"\b(?:const\s+)?(?:juce::)?String\s+" + re.escape(name) + r"\s*\(", self.code[lo:pos]):
            po = lo + m.end() - 1
            pc = match(self.code, po)
            if best is None or lo + m.start() > best[0]:
                best = (lo + m.start(), "juce::String (" + self.code[po + 1:pc] + ")")
        return best

    def creator_type(self, call_name, args_text):
        m = re.match(r"(?:std::)?make_unique\s*<\s*(?:juce::)?(\w+)\s*>", call_name)
        if not m:
            return None
        t = self.aliases.get(m.group(1), m.group(1))
        return AP_TYPES.get(t)

    # --- expression evaluation -> ("lit", text) or ("expr", text)
    def ev(self, expr, pos, env, depth=0):
        expr = expr.strip()
        if depth > 10:
            return ("expr", expr)
        while expr.startswith("(") and match(expr, 0) == len(expr) - 1:
            expr = expr[1:-1].strip()
        if expr in env:
            return env[expr]
        t = split_top(expr, "?")
        if len(t) >= 2:
            alt = split_top("?".join(t[1:]), ":")
            if len(alt) >= 2:
                yes, no = alt[0], ":".join(alt[1:])
                verdict = decide(self.subst(t[0], pos, env).replace(" ", ""))
                if verdict is not None:
                    return self.ev(yes if verdict else no, pos, env, depth + 1)
                a, b = self.ev(yes, pos, env, depth + 1), self.ev(no, pos, env, depth + 1)
                if a[0] == "lit" and b[0] == "lit":
                    opts = []
                    for v in (a[1], b[1]):
                        for o in (v[1:-1].split("|") if v.startswith("{") and v.endswith("}") and "|" in v else [v]):
                            if o not in opts:
                                opts.append(o)
                    return ("lit", "{" + "|".join(opts) + "}")
                return ("expr", "%s | %s" % (a[1], b[1]))
        pieces = split_top(expr, "+")
        if len(pieces) > 1:
            vals = [self.ev(p, pos, env, depth + 1) for p in pieces]
            if any(v[0] == "lit" for v in vals):
                return ("lit", "".join(v[1] if v[0] == "lit" else "{n}" for v in vals))
            return ("expr", tidy(expr))
        m = re.fullmatch(r'"((?:[^"\\]|\\.)*)"', expr)
        if m:
            return ("lit", m.group(1))
        m = re.fullmatch(r"(?:juce::)?ParameterID\s*[{(](.*)[})]", expr, re.S) or re.fullmatch(r"\{(.*),\s*\w+\s*\}", expr, re.S)
        if m and split_top(m.group(1)):
            return self.ev(split_top(m.group(1))[0], pos, env, depth + 1)
        m = re.fullmatch(r"(?:juce::)?String\s*(?:\(\s*(?:juce::)?CharPointer_UTF8\s*)?\((.*)\)\s*\)?", expr, re.S)
        if m and expr.count("(") >= 1:
            inner = self.ev(m.group(1), pos, env, depth + 1)
            return inner if inner[0] == "lit" else ("expr", "{n}")
        m = re.fullmatch(r"((?:\w+::)*)(\w+)", expr)
        if m:
            name = m.group(2)
            if not m.group(1):
                lv = self.local_var(name, pos)
                if lv:
                    return self.ev(lv[1], lv[0], env, depth + 1)
            if name in self.strings and len(self.strings[name]) == 1:
                return ("lit", next(iter(self.strings[name])))
            return ("expr", expr)
        m = re.fullmatch(r"(\w+)\s*\[\s*\(?\s*(?:size_t\s*\))?\s*\w+\s*\]", expr)
        if m and m.group(1) in self.str_arrays:
            return ("lit", "{" + "|".join(self.str_arrays[m.group(1)]) + "}")
        m = re.fullmatch(r"([\w:]+)\s*\((.*)\)", expr, re.S)
        if m and match(expr, expr.index("(")) == len(expr) - 1:
            fname = m.group(1).split("::")[-1]
            f = self.lookup_fn(fname, pos)
            if f and f.ret:
                args = split_top(m.group(2))
                sub = {}
                for i, pname in enumerate(f.params):
                    if i < len(args):
                        sub[pname] = self.ev(args[i], pos, env, depth + 1)
                return self.ev(f.ret, f.start, sub, depth + 1)
        return ("expr", tidy(expr))

    def subst(self, expr, pos, env):
        """Non-string expression with bindings and numeric constants filled in."""
        def rep(m):
            w = m.group(0)
            base = w.split("::")[-1]
            if w in env:
                return ('"%s"' % env[w][1]) if env[w][0] == "lit" else env[w][1]
            if base in self.numbers and len(self.numbers[base]) == 1:
                return next(iter(self.numbers[base]))
            return w
        return tidy(re.sub(r"(?<![\w.\"])(?:\w+::)*[A-Za-z_]\w*(?![\w\"])", rep, expr))

    def choices(self, expr, pos, env):
        e = expr.strip()
        if e in env and env[e][0] == "expr" and env[e][1].startswith("["):
            return env[e][1]
        m = re.fullmatch(r"(?:juce::)?(?:StringArray)?\s*\{(.*)\}", e, re.S)
        if m:
            items = re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1))
            if items:
                return "[" + ", ".join(items) + "]"
        m = re.fullmatch(r"(\w+)\s*\(\s*\)", e)
        if m:
            f = self.lookup_fn(m.group(1), pos)
            if f and f.ret:
                return self.choices(f.ret, f.start, {})
        if e in env:
            return env[e][1]
        return tidy(e)

    # --- walk
    def calls_in(self, start, end):
        """Parameter-creating calls (creator or helper) directly inside [start, end)."""
        out = []
        for m in re.finditer(r"((?:std::)?make_unique\s*<\s*[\w:]+\s*>|\b[A-Za-z_]\w*)\s*\(", self.code[start:end]):
            p = start + m.start()
            name = m.group(1)
            po = start + m.end() - 1
            pc = match(self.code, po)
            ctype = self.creator_type(name, "")
            if ctype:
                out.append((p, "creator", ctype, self.code[po + 1:pc]))
            elif name in self.helpers:
                f = self.lookup_fn(name, p)
                if f and f.kind == "func" and not (f.start < p < f.end):
                    out.append((p, "helper", name, self.code[po + 1:pc]))
        return out

    def parse(self):
        # helpers: functions whose body creates parameters (directly or through other helpers)
        self.helpers = set()
        creates = {}
        for f in self.funcs:
            body = self.code[f.start:f.end]
            creates[f] = bool(re.search(r"make_unique\s*<\s*(?:juce::)?(\w+)\s*>", body)) and any(
                AP_TYPES.get(self.aliases.get(t, t)) for t in re.findall(r"make_unique\s*<\s*(?:juce::)?(\w+)\s*>", body))
        changed = True
        names_creating = {f.name for f in self.funcs if creates[f] and f.kind == "func"}
        while changed:
            changed = False
            for f in self.funcs:
                if f.kind != "func" or f.name in names_creating:
                    continue
                body = self.code[f.start:f.end]
                if any(re.search(r"\b%s\s*\(" % re.escape(h), body) for h in names_creating):
                    names_creating.add(f.name)
                    changed = True
        self.helpers = names_creating
        called = set()
        for f in self.funcs:
            if f.kind == "func" and f.name in self.helpers:
                body = self.code[f.start:f.end]
                for h in self.helpers:
                    if h != f.name and re.search(r"\b%s\s*\(" % re.escape(h), body):
                        called.add(h)
        roots = [f for f in self.funcs if f.kind == "func" and f.name in self.helpers and f.name not in called]
        rows = []
        for r in roots:
            self.walk(r, {}, [], rows, 0)
        return rows

    def loops_at(self, f, pos):
        hs = []
        for (s, e, h) in loop_ranges(self.code, f.start, f.end):
            if s < pos < e:
                hs.append(h)
        return hs

    def loop_label(self, header, env, pos):
        h = squash(header)
        if ":" in h and ";" not in h:
            var, rng = h.split(":", 1)
            items = re.findall(r'"([^"]*)"', rng)
            var = var.split()[-1].lstrip("*&")
            return "%s in %s" % (var, "/".join(items) if items else tidy(rng))
        parts = [p.strip() for p in h.split(";")]
        if len(parts) == 3:
            return self.subst(parts[1], pos, env).replace(" ", "")
        return tidy(h)

    def walk(self, f, env, loops, rows, depth):
        if depth > 6:
            return
        for (p, kind, what, args_text) in self.calls_in(f.start + 1, f.end):
            here_loops = loops + [self.loop_label(h, env, p) for h in self.loops_at(f, p)]
            skip = False
            for (bs, be, cond, earlier) in branch_ranges(self.code, f.start + 1, f.end):
                if not (bs <= p <= be):
                    continue
                prior = [decide(self.subst(c, p, env).replace(" ", "")) for c in earlier]
                own = decide(self.subst(cond, p, env).replace(" ", "")) if cond else None
                if any(v is True for v in prior) or own is False:
                    skip = True
                    break
                if cond and own is None:
                    here_loops = here_loops + ["if " + self.subst(cond, p, env)]
                elif not cond and earlier and not all(v is False for v in prior):
                    here_loops = here_loops + ["else"]
            if skip:
                continue
            args = split_top(args_text)
            if kind == "creator":
                roles = ROLES[what]
                vals = dict(zip(roles, args))
                row = {"type": what, "loops": here_loops}
                pid = self.ev(vals.get("id", "?"), p, env)
                row["id"] = pid[1] if pid[0] == "lit" else "`%s`" % pid[1]
                nm = self.ev(vals.get("name", "?"), p, env)
                row["name"] = nm[1] if nm[0] == "lit" else "`%s`" % nm[1]
                if what == "float":
                    row["range"] = self.range_text(vals.get("range", "?"), p, env)
                elif what == "int":
                    row["range"] = "%s..%s" % (self.subst(vals.get("lo", "?"), p, env), self.subst(vals.get("hi", "?"), p, env))
                elif what == "choice":
                    row["range"] = self.choices(vals.get("choices", "?"), p, env)
                else:
                    row["range"] = "on/off"
                d = vals.get("default", "?")
                dv = self.subst(d, p, env)
                if what == "choice" and re.fullmatch(r"\d+", dv) and row["range"].startswith("["):
                    items = [x.strip() for x in row["range"][1:-1].split(",")]
                    if int(dv) < len(items):
                        dv = "%s (%s)" % (dv, items[int(dv)])
                row["default"] = dv
                rows.append(row)
            else:
                h = self.lookup_fn(what, p)
                sub = {}
                for i, pname in enumerate(h.params):
                    if i < len(args):
                        a = args[i]
                        v = self.ev(a, p, env)
                        if v[0] == "expr":
                            cv = self.choices(a, p, env)
                            rt = self.range_text(a, p, env)
                            if cv.startswith("["):
                                v = ("expr", cv)
                            elif ".." in rt and ".." not in a:
                                v = ("expr", rt)
                            else:
                                v = ("expr", self.subst(a, p, env))
                        sub[pname] = v
                self.walk(h, sub, here_loops, rows, depth + 1)

    def range_text(self, expr, pos, env, depth=0):
        e = expr.strip()
        if e in env:
            return env[e][1]
        if depth < 4 and re.fullmatch(r"[A-Za-z_]\w*", e):
            f = self.enclosing(pos)
            lo = f.start if f else 0
            decl = None
            for m in re.finditer(r"NormalisableRange\s*<\s*float\s*>\s+" + re.escape(e) + r"\s*([({])", self.code[lo:pos]):
                decl = lo + m.end() - 1
            if decl is not None:
                close = match(self.code, decl)
                txt = self.range_text("NormalisableRange<float> (" + self.code[decl + 1:close] + ")", pos, env, depth + 1)
                sk = re.search(re.escape(e) + r"\s*\.\s*setSkewForCentre\s*\(([^;]*)\)\s*;", self.code[close:pos])
                if sk:
                    txt += " skew centre " + self.subst(sk.group(1), pos, env)
                return txt
        m = re.fullmatch(r"(\w+)\s*\((.*)\)", e, re.S)
        if depth < 4 and m and match(e, e.index("(")) == len(e) - 1:
            f = self.lookup_fn(m.group(1), pos)
            if f and f.ret and f.kind == "func" and f.ret.startswith(("{", "juce::NormalisableRange", "NormalisableRange")):
                args = split_top(m.group(2))
                sub = {}
                for i, pname in enumerate(f.params):
                    if i < len(args):
                        sub[pname] = ("expr", self.subst(args[i], pos, env))
                if len(args) >= len(f.params):
                    return self.range_text(f.ret, f.start, sub, depth + 1)
        m = re.fullmatch(r"(?:juce::)?NormalisableRange\s*<\s*float\s*>\s*\((.*)\)", e, re.S)
        m2 = re.fullmatch(r"\{(.*)\}", e, re.S)
        inner = m.group(1) if m else (m2.group(1) if m2 else None)
        if inner is not None:
            raw = split_top(inner)
            if len(raw) >= 3 and "[" in raw[2] and "]" in raw[2]:
                return "%s..%s (custom mapping)" % (self.subst(raw[0], pos, env), self.subst(raw[1], pos, env))
            a = [self.subst(x, pos, env) for x in raw]
            if len(a) >= 2:
                s = "%s..%s" % (a[0], a[1])
                if len(a) >= 3 and a[2] not in ("0", "0.0"):
                    s += " step " + a[2]
                if len(a) >= 4:
                    s += " skew " + a[3]
                return s
        return self.subst(e, pos, env)


def row_multiplicity(r):
    """(parameter objects this row stands for, exact?) from its repeat count and loop headers."""
    n, exact = r.get("count", 1), True
    for lp in r.get("loops", []):
        m = re.match(r"^\s*\w+\s*<\s*(\d+)\s*$", lp)
        if m:
            n *= int(m.group(1))
            continue
        m = re.match(r"^\s*\w+\s+in\s+\{(.*)\}\s*$", lp)
        if m:
            n *= len([x for x in split_top(m.group(1), ",") if x.strip()])
            continue
        exact = False  # an undecided if/else or a loop bound we could not resolve
    return n, exact


def dedupe(rows):
    out, seen = [], {}
    for r in rows:
        key = (r["id"], r["type"], r["name"], r["range"], r["default"], tuple(r["loops"]))
        if key in seen:
            seen[key]["count"] += 1
            continue
        r = dict(r)
        r["count"] = 1
        seen[key] = r
        out.append(r)
    return out


