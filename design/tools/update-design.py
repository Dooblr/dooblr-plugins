def first_sentence(text):
    t = squash(text)
    t = re.sub(r"^[#*/\-=\s]+", "", t)
    m = re.match(r"(.+?[^.\s][.!?])(\s|$)", t)
    s = m.group(1) if m else t
    s = s.rstrip(":;,").strip()
    if len(s) > MAX_ROLE:
        s = s[:MAX_ROLE - 3].rsplit(" ", 1)[0] + "..."
    return s


def comment_role(src, ext):
    lines = src.splitlines()
    if ext in (".sh", ".py", ".cmake", ".txt", ".yml", ".yaml", ".ps1") or os.path.basename(ext) == "":
        if ext == ".py":
            m = re.search(r'^(?:#![^\n]*\n)?(?:#[^\n]*\n|\s)*(?:"""|\'\'\')(.*?)(?:"""|\'\'\')', src, re.S)
            if m:
                return first_sentence(m.group(1))
        buf = []
        for ln in lines[:40]:
            s = ln.strip()
            if s.startswith("#!"):
                continue
            if s.startswith("#"):
                body = s.lstrip("#").strip()
                if body:
                    buf.append(body)
                elif buf:
                    break
            elif s and buf:
                break
            elif s and not buf and ext not in (".txt", ".cmake"):
                break
        return first_sentence(" ".join(buf)) if buf else ""
    if ext == ".md":
        for ln in lines:
            if ln.startswith("#"):
                return first_sentence(ln.lstrip("#"))
        return ""
    # C-like, in order of preference: a descriptive comment at the top of the file (before any
    # code), the comment right above the first class/struct, then the first descriptive comment.
    # Short labels, version tags and banner lines are skipped.
    head = src[:30000]
    blocks = []
    for m in re.finditer(r"/\*\*?(.*?)\*/|((?:^[ \t]*//[^\n]*\n)+)", head, re.S | re.M):
        body = m.group(1) if m.group(1) is not None else re.sub(r"^[ \t]*//+ ?", "", m.group(2), flags=re.M)
        body = re.sub(r"^\s*\*+ ?", "", body, flags=re.M)
        paras = [p for p in re.split(r"\n\s*\n", body) if p.strip()]
        if not paras:
            continue
        sent = first_sentence(paras[0])
        if len(sent.split()) < 4 or re.match(r"v?\d+(\.\d+)+\b", sent) or not re.search(r"[A-Za-z]", sent):
            continue
        blocks.append((m.start(), m.end(), sent))
    if not blocks:
        return ""
    code = strip_comments(head)
    first_code = re.search(r"^[ \t]*(?!#|namespace\b|\{|\}|using\b|$)\S", code, re.M)
    if first_code and blocks[0][0] < first_code.start():
        return blocks[0][2]
    cls = re.search(r"^[ \t]*(?:template\s*<[^>]*>\s*)?(?:class|struct)\s+\w+[^;]*$", code, re.M)
    if cls:
        for (s0, e0, sent) in blocks:
            if e0 <= cls.start() and not head[e0:cls.start()].strip():
                return sent
    return blocks[0][2]


CLASS_RE = re.compile(r"^[ \t]*(class|struct)\s+(?:JUCE_API\s+)?(\w+)(?:\s+final)?\s*(?::\s*([^{;]+))?\{", re.M)


def classes(src):
    out = []
    for m in CLASS_RE.finditer(strip_comments(src)):
        indent = len(m.group(0)) - len(m.group(0).lstrip())
        if indent > 8:
            continue
        bases = []
        if m.group(3):
            for b in split_top(m.group(3)):
                b = re.sub(r"^(public|private|protected)\s+", "", b.strip()).replace("juce::", "")
                bases.append(squash(b))
        out.append((m.group(2), bases))
    return out


def file_entries(idx, files, root):
    """[(display path, role)] with .h/.cpp/.mm pairs merged."""
    groups = {}
    for f in files:
        rel = f[len(root) + 1:]
        base, ext = os.path.splitext(rel)
        if ext.lower() in SKIP_EXT or os.path.basename(rel) in (".gitignore",):
            continue
        if ext in (".h", ".hpp", ".cpp", ".mm", ".c"):
            groups.setdefault(base, []).append(ext)
        else:
            groups.setdefault(rel, []).append("")
    idx.load([root + "/" + (k + e) for k, es in groups.items() for e in es])
    out = []
    for key in sorted(groups):
        exts = sorted(groups[key], key=lambda e: {".h": 0, ".hpp": 0, ".cpp": 1, ".mm": 2, ".c": 1}.get(e, 3))
        if exts == [""]:
            path = key
            src = idx.text(root + "/" + key) or ""
            ext = os.path.splitext(key)[1].lower()
            base = os.path.basename(key)
            if base == "CMakeLists.txt":
                tg = re.findall(r"(?:juce_add_\w+|add_executable|add_library)\s*\(\s*(\w+)", src)
                role = "CMake build" + ((": " + ", ".join(sorted(set(tg)))) if tg else "")
            elif ext == ".json":
                role = "JSON data" if not base == "package.json" else "npm package: scripts and dev dependencies"
            elif ext == ".maxpat":
                role = "Max patcher (source of the device)"
            elif ext in (".js", ".mm", ".c"):
                role = comment_role(src, ext)
            else:
                role = comment_role(src, ext)
            if base == "README.md":
                role = "Readme: " + (role or "")
            out.append((path, role))
            continue
        path = key + (exts[0] if len(exts) == 1 else ".{" + ",".join(e[1:] for e in exts) + "}")
        role = ""
        cls = []
        for e in exts:
            src = idx.text(root + "/" + key + e) or ""
            if not role:
                role = comment_role(src, e)
            if (e in (".h", ".hpp") or len(exts) == 1) and not re.match(r"(Tests|tests)/", key):
                cls += [c for c, _ in classes(src)]
        if cls:
            shown = ", ".join(cls[:4]) + (", ..." if len(cls) > 4 else "")
            role = (role + " [" + shown + "]") if role else "[" + shown + "]"
        out.append((path, role))
    return out


