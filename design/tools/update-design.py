"""Regenerate the machine-maintained parts of the dooblr design folder.

For every plugin folder at the repo root (dooblr-*/ with a CMakeLists.txt or package.json) this
writes the block between the AUTO-GENERATED markers in design/plugins/<plugin>.md, and the
generated table in design/INDEX.md. Hand-written text outside the markers is never touched.

Everything is read from the git index (what `git add` staged, which equals HEAD on a clean
checkout), so unstaged work in progress never leaks into the design files and the output is
the same on every machine. Python 3 standard library only.

    python3 design/tools/update-design.py                 # every plugin + INDEX.md
    python3 design/tools/update-design.py dooblr-kick     # one plugin + INDEX.md
    python3 design/tools/update-design.py --check         # exit 1 if anything is out of date
    python3 design/tools/update-design.py --print-changed # list the files it rewrote
"""

