// Build the device folder from the sources:
//   device/dooblr-titan/dooblr_titan.js     engine (manifest order) + src/max/main.js
//   device/dooblr-titan/dooblr_roll.js      src/max/roll.js
//   device/dooblr-titan/dooblr_previews.js  src/max/previews.js
//   device/dooblr-titan/dooblr-titan.amxd   src/patcher/dooblr-titan.maxpat in an unfrozen amxd
'use strict';
const fs = require('fs');
const path = require('path');
const amxd = require('./amxd');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'device', 'dooblr-titan');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

function read(rel) { return fs.readFileSync(path.join(ROOT, rel), 'utf8'); }

function header(name, sources) {
  return '// ' + name + ' - dooblr-titan v' + pkg.version + '\n' +
    '// GENERATED by scripts/build.js from ' + sources.join(', ') + '. Do not edit; edit the sources and rebuild.\n\n';
}

function buildController() {
  const manifest = JSON.parse(read('src/engine/manifest.json'));
  const sources = manifest.map((f) => 'src/engine/' + f).concat(['src/max/main.js']);
  const body = sources.map((rel) => '// ---- ' + rel + ' ----\n' + read(rel).replace(/\s+$/, '') + '\n').join('\n');
  return header('dooblr_titan.js', ['src/engine/*', 'src/max/main.js']) + body;
}

function main() {
  fs.mkdirSync(OUT, { recursive: true });
  const controller = buildController();
  const roll = header('dooblr_roll.js', ['src/max/roll.js']) + read('src/max/roll.js');
  const previews = header('dooblr_previews.js', ['src/max/previews.js']) + read('src/max/previews.js');
  const patcher = JSON.parse(read('src/patcher/dooblr-titan.maxpat'));
  const device = amxd.write(patcher, { type: 'midi' });

  const back = amxd.read(device);
  if (JSON.stringify(back.patcher) !== JSON.stringify(patcher)) { throw new Error('amxd round trip changed the patcher'); }

  fs.writeFileSync(path.join(OUT, 'dooblr_titan.js'), controller);
  fs.writeFileSync(path.join(OUT, 'dooblr_roll.js'), roll);
  fs.writeFileSync(path.join(OUT, 'dooblr_previews.js'), previews);
  fs.writeFileSync(path.join(OUT, 'dooblr-titan.amxd'), device);
  console.log('built ' + path.relative(ROOT, OUT) + '/ (amxd ' + device.length + ' bytes, ' +
    patcher.patcher.boxes.length + ' boxes, ' + patcher.patcher.lines.length + ' lines)');
}

main();
