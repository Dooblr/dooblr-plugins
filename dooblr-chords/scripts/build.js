// Build the device folder from the sources:
//   device/dooblr-chords/dooblr_chords.js   engine (manifest order) + src/max/main.js
//   device/dooblr-chords/dooblr_blocks.js   src/max/blocks.js
//   device/dooblr-chords/dooblr-chords.amxd src/patcher/dooblr-chords.maxpat in an unfrozen amxd
'use strict';
const fs = require('fs');
const path = require('path');
const amxd = require('./amxd');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'device', 'dooblr-chords');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

function read(rel) { return fs.readFileSync(path.join(ROOT, rel), 'utf8'); }

function header(name, sources) {
  return '// ' + name + ' - dooblr-chords v' + pkg.version + '\n' +
    '// GENERATED by scripts/build.js from ' + sources.join(', ') + '. Do not edit; edit the sources and rebuild.\n\n';
}

function buildController() {
  const manifest = JSON.parse(read('src/engine/manifest.json'));
  const sources = manifest.map((f) => 'src/engine/' + f).concat(['src/max/main.js']);
  const body = sources.map((rel) => '// ---- ' + rel + ' ----\n' + read(rel).replace(/\s+$/, '') + '\n').join('\n');
  return header('dooblr_chords.js', ['src/engine/*', 'src/max/main.js']) + body;
}

function main() {
  fs.mkdirSync(OUT, { recursive: true });
  const controller = buildController();
  const blocks = header('dooblr_blocks.js', ['src/max/blocks.js']) + read('src/max/blocks.js');
  const patcher = JSON.parse(read('src/patcher/dooblr-chords.maxpat'));
  const device = amxd.write(patcher, { type: 'midi' });

  // Round-trip check before anything is written.
  const back = amxd.read(device);
  if (JSON.stringify(back.patcher) !== JSON.stringify(patcher)) { throw new Error('amxd round trip changed the patcher'); }

  fs.writeFileSync(path.join(OUT, 'dooblr_chords.js'), controller);
  fs.writeFileSync(path.join(OUT, 'dooblr_blocks.js'), blocks);
  fs.writeFileSync(path.join(OUT, 'dooblr-chords.amxd'), device);
  console.log('built ' + path.relative(ROOT, OUT) + '/ (amxd ' + device.length + ' bytes, ' +
    patcher.patcher.boxes.length + ' boxes, ' + patcher.patcher.lines.length + ' lines)');
}

main();
