'use strict';
const fs = require('fs');
const path = require('path');
const amxd = require('./amxd');

const ROOT = path.join(__dirname, '..');
const CHORDS = path.join(ROOT, '..', 'dooblr-chords');
const OUT = path.join(ROOT, 'device', 'dooblr-chord-receiver');
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

const SHARED = [
  'src/engine/theory.js',
  'src/engine/chords.js',
  'src/engine/protocol.js',
  'src/engine/snap.js'
];

function read(abs) { return fs.readFileSync(abs, 'utf8'); }

function header(name, sources) {
  return '// ' + name + ' - dooblr-chord-receiver v' + pkg.version + '\n' +
    '// GENERATED by scripts/build.js from ' + sources.join(', ') + '. Do not edit; edit the sources and rebuild.\n\n';
}

function buildController() {
  const sources = SHARED.map((rel) => ({ rel: 'dooblr-chords/' + rel, abs: path.join(CHORDS, rel) }))
    .concat([{ rel: 'src/max/main.js', abs: path.join(ROOT, 'src/max/main.js') }]);
  const body = sources.map((s) => '// ---- ' + s.rel + ' ----\n' + read(s.abs).replace(/\s+$/, '') + '\n').join('\n');
  return header('dooblr_chord_receiver.js', sources.map((s) => s.rel)) + body;
}

function main() {
  fs.mkdirSync(OUT, { recursive: true });
  const controller = buildController();
  const display = header('dooblr_chord_receiver_ui.js', ['src/max/display.js']) + read(path.join(ROOT, 'src/max/display.js'));
  const patcher = JSON.parse(read(path.join(ROOT, 'src/patcher/dooblr-chord-receiver.maxpat')));
  const device = amxd.write(patcher, { type: 'midi' });
  const back = amxd.read(device);
  if (JSON.stringify(back.patcher) !== JSON.stringify(patcher)) { throw new Error('amxd round trip changed the patcher'); }
  fs.writeFileSync(path.join(OUT, 'dooblr_chord_receiver.js'), controller);
  fs.writeFileSync(path.join(OUT, 'dooblr_chord_receiver_ui.js'), display);
  fs.writeFileSync(path.join(OUT, 'dooblr-chord-receiver.amxd'), device);
  console.log('built ' + path.relative(ROOT, OUT) + '/ (amxd ' + device.length + ' bytes, ' +
    patcher.patcher.boxes.length + ' boxes, ' + patcher.patcher.lines.length + ' lines)');
}

main();
